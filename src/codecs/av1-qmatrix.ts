const decodeBase64 = (encoded: string): Uint8Array => {
  const output = new Uint8Array(Math.floor((encoded.length * 3) / 4))
  let accumulator = 0
  let bits = 0
  let offset = 0
  for (const character of encoded) {
    if (character === '=') break
    const value = base64Alphabet.indexOf(character)
    if (value < 0) continue
    accumulator = accumulator * 64 + value
    bits += 6
    if (bits >= 8) {
      bits -= 8
      output[offset] = (accumulator >>> bits) & 255
      offset += 1
      accumulator &= (1 << bits) - 1
    }
  }
  return output.subarray(0, offset)
}

// Normative inverse quantization matrices from AV1 specification section
// 9.5.3, packed only to keep the portable JavaScript module compact.
const packedMatrices = decodeBase64(packedMatrixData)

const readExtendedLength = (
  data: Uint8Array,
  position: { value: number },
  initial: number,
): number => {
  if (initial !== 15) return initial
  let length = initial
  let next = 255
  while (next === 255) {
    next = data[position.value] ?? 0
    position.value += 1
    length += next
  }
  return length
}

let matrixCache: Uint8Array | undefined

const unpackMatrices = (): Uint8Array => {
  if (matrixCache) return matrixCache
  const output = new Uint8Array(matrixDataSize)
  const source = { value: 0 }
  let destination = 0
  while (source.value < packedMatrices.length) {
    const token = packedMatrices[source.value] ?? 0
    source.value += 1
    const literals = readExtendedLength(packedMatrices, source, token >>> 4)
    const literalEnd = source.value + literals
    if (literalEnd > packedMatrices.length || destination + literals > output.length) {
      throw new Error('AV1 quantization matrix literals are corrupt')
    }
    output.set(packedMatrices.subarray(source.value, literalEnd), destination)
    source.value = literalEnd
    destination += literals
    if (source.value === packedMatrices.length) break
    const low = packedMatrices[source.value]
    const high = packedMatrices[source.value + 1]
    if (low === undefined || high === undefined) {
      throw new Error('AV1 quantization matrix reference is truncated')
    }
    source.value += 2
    const distance = low | (high << 8)
    const match = readExtendedLength(packedMatrices, source, token & 15) + 4
    if (distance < 1 || distance > destination || destination + match > output.length) {
      throw new Error('AV1 quantization matrix reference is invalid')
    }
    for (let index = 0; index < match; index += 1) {
      output[destination] = output[destination - distance] ?? 0
      destination += 1
    }
  }
  if (destination !== output.length) throw new Error('AV1 quantization matrix data is incomplete')
  matrixCache = output
  return output
}

export const av1InverseQuantizationMatrix = (
  level: number,
  plane: 0 | 1 | 2,
  width: 4 | 8 | 16 | 32 | 64,
  height: 4 | 8 | 16 | 32 | 64,
): Uint8Array | undefined => {
  if (level === 15) return undefined
  if (!Number.isInteger(level) || level < 0 || level > 15) {
    throw new Error(`Invalid AV1 quantization matrix level ${level}`)
  }
  const offset = transformOffsets.get(`${width}x${height}`)
  if (offset === undefined)
    throw new Error(`Invalid AV1 quantization matrix size ${width}x${height}`)
  const matrices = unpackMatrices()
  const base = (level * 2 + (plane === 0 ? 0 : 1)) * matrixSetSize + offset
  return matrices.subarray(base, base + Math.min(width, 32) * Math.min(height, 32))
}
