export interface LibraryComparison {
  readonly id: string
  readonly name: string
  readonly version: string
  readonly packageName: string | null
  readonly url: string
  readonly implementation: 'pure-javascript' | 'native-wrapper'
  readonly runtime: {
    readonly pureJavaScript: ComparisonValue
    readonly browser: ComparisonValue
    readonly node: ComparisonValue
    readonly wasmRequired: ComparisonValue
    readonly nativeRequired: ComparisonValue
  }
  readonly tiff: TiffCapabilities
  readonly conformanceEngine?: 'purejsimage' | 'geotiff' | 'utif2' | 'tiff' | 'image-js' | 'jimp'
}

const value = (status: ComparisonStatus, evidence: string, note?: string): ComparisonValue =>
  Object.freeze({ status, evidence, ...(note === undefined ? {} : { note }) })

const yes = (evidence: string, note?: string): ComparisonValue => value('yes', evidence, note)
const partial = (evidence: string, note: string): ComparisonValue =>
  value('partial', evidence, note)
const no = (evidence: string, note?: string): ComparisonValue => value('no', evidence, note)

