import { createHash } from 'node:crypto'
import { deflateSync, inflateSync } from 'node:zlib'
import { PNG } from 'pngjs'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { pngCodec } from '../src/codec-entries/png.ts'
import { createImageLibraryForPlatform } from '../src/image-core.ts'
import { createNodeImageLibrary } from '../src/node-image.ts'
import { nodePlatform } from '../src/node-platform.ts'
import { nodeRuntime } from '../src/node-runtime.ts'
import {
  adler32,
  combineAdler32,
  deflateChunkBytes,
  ParallelDeflateEncoder,
} from '../src/node-parallel-deflate.ts'

const library = createNodeImageLibrary([pngCodec])
const pixels = (width: number, height: number): PNG => {
  const image = new PNG({ width, height })
  for (let i = 0; i < image.data.length; i++) image.data[i] = (i * 37 + (i >>> 9)) & 255
  return image
}
const sha256 = (bytes: Uint8Array): string => createHash('sha256').update(bytes).digest('hex')

afterEach(() => vi.unstubAllEnvs())

describe('parallel PNG compression', () => {
  it('keeps pinned base PNG bytes with threads omitted, set to one, or unavailable', async () => {
    const bytes = PNG.sync.write(pixels(511, 397))
    // Generated by 2e8befb0960fe65d1adc9fec05cfa0618495af1d with Node 24.
    const pinned = 'e4befd02bcd8e29c9414e13b858ac77597283c78ae569bd9e7800de5945bfed3'
    const oneCpu = createImageLibraryForPlatform([pngCodec], {
      ...nodePlatform,
      runtime: { ...nodePlatform.runtime, availableParallelism: () => 1 },
    })
    for (const image of [
      await library.open(bytes),
      await library.open(bytes, { threads: 1 }),
      await oneCpu.open(bytes, { threads: 4 }),
    ]) {
      expect(sha256(await image.png().toBuffer())).toBe(pinned)
    }
    vi.stubEnv('UV_THREADPOOL_SIZE', '1')
    expect(sha256(await (await library.open(bytes, { threads: 4 })).png().toBuffer())).toBe(pinned)
  })

  it.each([0, -1, 1.5, NaN, Infinity, Number.MAX_SAFE_INTEGER + 1])(
    'rejects invalid thread count %s at open',
    async (threads) => {
      await expect(library.open(new Uint8Array(), { threads })).rejects.toMatchObject({
        code: 'INVALID_INPUT',
        message: 'threads must be a positive safe integer',
      })
    },
  )

  it.each([
    [17, 13, 0],
    [513, 197, 0],
    [819, 193, 9],
    [511, 397, 1],
    [1, 1777, 9],
    [753, 519, 6],
  ])('preserves all RGBA pixels at %i by %i, level %i', async (width, height, compressionLevel) => {
    const source = pixels(width, height)
    const image = await library.open(PNG.sync.write(source), { threads: 4 })
    const output = PNG.sync.read(await image.png({ compressionLevel }).toBuffer())
    expect(output.width).toBe(width)
    expect(output.height).toBe(height)
    expect(output.data.equals(source.data)).toBe(true)
  })

  it('reuses bounded filter scratch and lets the PNG writer handle wider bands', async () => {
    const encoder = new ParallelDeflateEncoder(2, { level: 6 }, async () => {})
    const band = encoder.inputBuffer(65536)
    expect(band).toBeInstanceOf(Uint8Array)
    expect(encoder.inputBuffer(32768)?.buffer).toBe(band?.buffer)
    expect(encoder.inputBuffer(deflateChunkBytes + 1)).toBeUndefined()
    await encoder.abort(new Error('done'))
  })

  it('keeps the job queue bounded for direct runtime callers', async () => {
    for (const threads of [NaN, Infinity, 0.5, 0]) {
      const encoder = await nodeRuntime.createParallelDeflateEncoder?.(
        { level: 6, strategy: 'default' },
        async () => {},
        threads,
        deflateChunkBytes * 4,
      )
      expect(encoder).toBeUndefined()
    }
  })

  it('combines independent Adler-32 checksums including a zero low sum', () => {
    const left = Buffer.alloc(257, 255)
    left[256] = 240
    expect(adler32(left) & 0xffff).toBe(0)
    for (const right of [Buffer.alloc(0), Buffer.from([1]), Buffer.alloc(65521 * 2 + 97, 251)]) {
      const reference = deflateSync(Buffer.concat([left, right]))
      expect(combineAdler32(adler32(left), adler32(right), right.length)).toBe(
        reference.readUInt32BE(reference.length - 4),
      )
    }
  })

  it.each([-1, 0, 1])(
    'handles an exact chunk boundary plus %i and mutable input',
    async (delta) => {
      const bytes = Buffer.alloc(2 * deflateChunkBytes + delta)
      for (let i = 0; i < bytes.length; i++) bytes[i] = (i * 113 + (i >>> 11)) & 255
      const output: Uint8Array[] = []
      const encoder = new ParallelDeflateEncoder(2, { level: 6 }, async (part) => {
        output.push(part)
      })
      const scratch = Buffer.alloc(65537)
      for (let i = 0; i < bytes.length; i += scratch.length) {
        const n = bytes.copy(scratch, 0, i, i + scratch.length)
        await encoder.write(scratch.subarray(0, n))
        scratch.fill(0)
      }
      await encoder.finish()
      expect(inflateSync(Buffer.concat(output)).equals(bytes)).toBe(true)
    },
  )

  it('waits for an outstanding sink write on abort and discards the queued jobs', async () => {
    const started = Promise.withResolvers<void>()
    const gate = Promise.withResolvers<void>()
    let writes = 0
    const encoder = new ParallelDeflateEncoder(2, { level: 6 }, async () => {
      writes++
      started.resolve()
      await gate.promise
    })
    const reason = new Error('stopped')
    const pendingWrite = encoder.write(new Uint8Array(3 * deflateChunkBytes))
    const rejected = expect(pendingWrite).rejects.toBe(reason)
    await started.promise
    let done = false
    const abort = encoder.abort(reason).then(() => {
      done = true
    })
    await new Promise<void>((resolve) => setImmediate(resolve))
    expect(done).toBe(false)
    gate.resolve()
    await Promise.all([abort, rejected])
    expect(writes).toBe(1)
    await expect(encoder.finish()).rejects.toBe(reason)
  })

  it('aborts the public pipeline during IDAT output before closing the sink', async () => {
    const controller = new AbortController()
    const reason = new Error('cancelled PNG')
    vi.stubEnv('UV_THREADPOOL_SIZE', '4')
    const multicore = createImageLibraryForPlatform([pngCodec], {
      ...nodePlatform,
      runtime: { ...nodePlatform.runtime, availableParallelism: () => 4 },
    })
    const image = await multicore.open(PNG.sync.write(pixels(753, 519)), { threads: 4 })
    const close = vi.fn(async () => {})
    const abort = vi.fn(async (_reason: unknown) => {})
    const write = vi.fn(async (chunk: Uint8Array) => {
      if (chunk.length === 4 && Buffer.from(chunk).toString('latin1') === 'IDAT') {
        controller.abort(reason)
      }
    })
    await expect(
      image.png().toSink({ write, close, abort }, { signal: controller.signal }),
    ).rejects.toBe(reason)
    expect(abort).toHaveBeenCalledExactlyOnceWith(reason)
    expect(close).not.toHaveBeenCalled()
    const writes = write.mock.calls.length
    await new Promise<void>((resolve) => setImmediate(resolve))
    expect(write.mock.calls).toHaveLength(writes)
  })

  it('propagates sink and compression failures and settles the queued jobs', async () => {
    const reason = new Error('sink failed')
    let writes = 0
    const sinkFailure = new ParallelDeflateEncoder(3, { level: 6 }, async () => {
      writes++
      throw reason
    })
    await sinkFailure.write(new Uint8Array(deflateChunkBytes * 2 + 1))
    await expect(sinkFailure.finish()).rejects.toBe(reason)
    await sinkFailure.abort(reason)
    expect(writes).toBe(1)

    const nativeFailure = new ParallelDeflateEncoder(2, { level: 11 }, async () => {
      writes++
    })
    await nativeFailure.write(new Uint8Array(deflateChunkBytes + 1))
    await expect(nativeFailure.finish()).rejects.toThrow()
    await nativeFailure.abort(reason)
    expect(writes).toBe(1)
  })
})
