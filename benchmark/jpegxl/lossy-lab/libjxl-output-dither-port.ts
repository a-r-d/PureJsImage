export function libjxlDitheredRgba(
  planes: readonly [Float64Array, Float64Array, Float64Array],
  width: number,
  height: number,
  originX = 0,
  originY = 0,
): Uint8Array {
  if (
    !Number.isSafeInteger(width) ||
    !Number.isSafeInteger(height) ||
    width < 1 ||
    height < 1 ||
    !Number.isSafeInteger(originX) ||
    !Number.isSafeInteger(originY) ||
    originX < 0 ||
    originY < 0 ||
    planes.some((p) => p.length !== width * height)
  )
    throw new Error('Invalid dither extent')
  const output = new Uint8Array(width * height * 4)
  for (let y = 0; y < height; y++)
    for (let x = 0; x < width; x++) {
      const p = y * width + x
      for (let c = 0; c < 3; c++) {
        const sample = planes[c]?.[p] ?? 0
        if (!Number.isFinite(sample)) throw new Error('Nonfinite dither sample')
        const noise =
            dither[((y + originY + c * 13) % 32) * 32 + ((x + originX + c * 23) % 32)] ?? 0,
          value = Math.max(
            0,
            Math.min(255, Math.fround(Math.fround(Math.fround(sample) * 255) + noise)),
          ),
          low = Math.floor(value),
          fraction = value - low
        output[p * 4 + c] = fraction < 0.5 ? low : fraction > 0.5 ? low + 1 : low + (low % 2)
      }
      output[p * 4 + 3] = 255
    }
  return output
}
