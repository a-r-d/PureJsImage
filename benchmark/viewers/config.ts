const packageEngine = (
  id: ViewerEngineId,
  family: ViewerFamily,
  packageName: string,
  packageVersion: string,
  implementation: ViewerEngineMetadata['implementation'],
  gpuRendering: boolean,
  wasmRequired: boolean,
  nativeBrowserPrimitives: readonly string[],
  inputModel: ViewerEngineMetadata['inputModel'],
  preparedSidecar = false,
  sidecarNote?: string,
): ViewerEngineMetadata =>
  Object.freeze({
    id,
    family,
    packageName,
    packageVersion,
    implementation,
    gpuRendering,
    wasmRequired,
    nativeBrowserPrimitives: Object.freeze([...nativeBrowserPrimitives]),
    inputModel,
    preparedSidecar,
    ...(sidecarNote === undefined ? {} : { sidecarNote }),
  })

